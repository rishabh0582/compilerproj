
#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <string.h>

#include "lexerDef.h"
#include "lexer.h"
#include "parserDef.h"
#include "parser.h"
int main(int argc, char *argv[]) {

    if (argc < 2) {
        
        printf("Usage: %s <sourcecodefile> [optional_output_file]\n", argv[0]);
        return 0;
    }
    
    int choice = -1;

    printf("\n================ COMPILER DRIVER ================\n");
    printf("(c) Both lexical and syntax analysis modules implemented\n");
    printf("=================================================\n");

    while (choice != 0) {

        printf("\nChoose Option:\n");
        printf("0 : Exit\n");
        printf("1 : Remove comments and print comment-free code\n");
        printf("2 : Print token list generated by lexer\n");
        printf("3 : Parse source code and print parse tree\n");
        printf("4 : Print total time taken by lexer + parser\n");

        scanf("%d", &choice);


        if (choice == 1) {

            printf("\n----- Comment Free Code -----\n");
            removeComments(argv[1]);
        }


        else if (choice == 2) {

            
            initializeLexer(argv[1]);
            tokenInfo tk;

            printf("\n%-10s %-20s %-20s\n", "Line", "Lexeme", "Token");
            printf("-------------------------------------------------------------\n");

            do {
                tk = getNextToken();
                printf("%-10d %-20s %-20s\n",
                       tk.lineNo,
                       tk.lexeme,
                       getTokenName(tk.token));

            } while (tk.token != TK_EOF);

        }


        else if (choice == 3) {

            
            Production grammar[MAX_RULES];
            int ruleCount = initializeGrammar(grammar);

            FirstAndFollow F = ComputeFirstAndFollowSets(grammar, ruleCount);

            ParseTable T;
            createParseTable(F, grammar, ruleCount, &T);
            ParseTree PT = parseInputSourceCode(argv[1], T, F, grammar, ruleCount);

            printParseTreeToTerminal(PT);
            printf("\n");
        }


        else if (choice == 4) {

            clock_t start_time, end_time;
            double total_CPU_time, total_CPU_time_in_seconds;

            start_time = clock();

            Production grammar[MAX_RULES];
            int ruleCount = initializeGrammar(grammar);

            FirstAndFollow F = ComputeFirstAndFollowSets(grammar, ruleCount);

            ParseTable T;
            createParseTable(F, grammar, ruleCount, &T);

            parseInputSourceCode(argv[1], T, F, grammar, ruleCount);

            end_time = clock();

            total_CPU_time = (double)(end_time - start_time);
            total_CPU_time_in_seconds = total_CPU_time / CLOCKS_PER_SEC;

            printf("\nTotal CPU time: %lf\n", total_CPU_time);
            printf("Total CPU time in seconds: %lf\n", total_CPU_time_in_seconds);
        }

        else if (choice != 0) {
            printf("Invalid Option.\n");
        }
    }

    printf("\nExiting Compiler Driver.\n");

    return 0;
}